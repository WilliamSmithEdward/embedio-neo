using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace EmbedIO.Generators
{
    /// <summary>
    /// Generates <c>WebApiControllerBinding&lt;TController&gt;</c> properties for classes marked with
    /// <c>GeneratedControllerBindingAttribute</c>, so Web API controllers register without reflection. Also generates minimal endpoint descriptors
    /// for static classes marked with <c>GeneratedEndpointBindingAttribute</c>.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class ControllerBindingGenerator : IIncrementalGenerator
    {
        internal const string AttributeMetadataName = "EmbedIO.WebApi.GeneratedControllerBindingAttribute";

        /// <inheritdoc />
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // Any partial type the emitter can reopen; Keyword() writes its declaration back.
            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeMetadataName,
                static (node, _) => node is ClassDeclarationSyntax
                    or RecordDeclarationSyntax
                    or StructDeclarationSyntax,
                static (attributeContext, cancellationToken) => BindingParser.Parse(attributeContext, cancellationToken)
            );

            var endpoints = context.SyntaxProvider.ForAttributeWithMetadataName(
                "EmbedIO.Endpoints.GeneratedEndpointBindingAttribute",
                static (node, _) => node is ClassDeclarationSyntax,
                static (attributeContext, cancellationToken) => BindingParser.ParseEndpoints(
                    attributeContext,
                    cancellationToken
                )
            );

            var trimAnalyzed = context.AnalyzerConfigOptionsProvider.Select(
                static (provider, _) => IsTrimAnalyzed(provider.GlobalOptions)
            );

            context.RegisterSourceOutput(
                endpoints.Combine(trimAnalyzed),
                static (output, input) => Emit(output, input.Left, input.Right)
            );
            context.RegisterSourceOutput(
                models.Combine(trimAnalyzed),
                static (output, input) => Emit(output, input.Left, input.Right)
            );
        }

        private static void Emit(SourceProductionContext output, BindingModel? model, bool trimAnalyzed)
        {
            if (model is null)
                return;

            foreach (var diagnostic in model.Diagnostics)
                output.ReportDiagnostic(diagnostic.ToDiagnostic());

            if (trimAnalyzed)
            {
                foreach (var diagnostic in model.TrimDiagnostics)
                    output.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (model.Source is null)
                return;

            // The marker makes the compiler treat the file as generated: analyzers skip it and
            // nullable analysis starts disabled. The code also compiles as C# 7.3.
            // The marker does not cover compiler warnings, and a binding calls whatever the
            // application declared: a deprecated controller or route still answers requests, so
            // the obsolete member is referenced here deliberately and must not warn in a
            // consumer's build (CS0612 and CS0618; an error-level [Obsolete] still fails).
            output.AddSource(
                model.HintName,
                SourceText.From(
                    "// <auto-generated/>\n#pragma warning disable CS0612, CS0618\n" + model.Source,
                    Encoding.UTF8
                )
            );
        }

        // The SDK makes these properties visible to analyzers when the trim or AOT analyzer is enabled.
        private static bool IsTrimAnalyzed(AnalyzerConfigOptions options) =>
            IsTrue(options, "build_property.EnableTrimAnalyzer") || IsTrue(options, "build_property.EnableAotAnalyzer");

        private static bool IsTrue(AnalyzerConfigOptions options, string key) =>
            options.TryGetValue(key, out var value) && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);
    }
}
