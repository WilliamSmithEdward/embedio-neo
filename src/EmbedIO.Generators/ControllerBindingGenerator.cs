using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace EmbedIO.Generators
{
    /// <summary>
    /// Generates <c>WebApiControllerBinding&lt;TController&gt;</c> properties for classes marked with
    /// <c>GeneratedControllerBindingAttribute</c>, so Web API controllers register without reflection.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class ControllerBindingGenerator : IIncrementalGenerator
    {
        internal const string AttributeMetadataName = "EmbedIO.WebApi.GeneratedControllerBindingAttribute";

        /// <inheritdoc />
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeMetadataName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (attributeContext, cancellationToken) => BindingParser.Parse(attributeContext, cancellationToken));

            var trimAnalyzed = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) => IsTrimAnalyzed(provider.GlobalOptions));

            context.RegisterSourceOutput(
                models.Combine(trimAnalyzed),
                static (output, input) => Emit(output, input.Left, input.Right));
        }

        private static void Emit(SourceProductionContext output, BindingModel? model, bool trimAnalyzed)
        {
            if (model is null)
                return;

            foreach (var diagnostic in model.Diagnostics)
                output.ReportDiagnostic(diagnostic.ToDiagnostic());

            if (trimAnalyzed)
            {
                foreach (var diagnostic in model.TrimDiagnostics)
                    output.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (model.Source is null)
                return;

            // The marker makes the compiler treat the file as generated: analyzers skip it and
            // nullable analysis starts disabled. The code also compiles as C# 7.3.
            output.AddSource(model.HintName, SourceText.From("// <auto-generated/>\n" + model.Source, Encoding.UTF8));
        }

        // The SDK makes these properties visible to analyzers when the trim or AOT analyzer is enabled.
        private static bool IsTrimAnalyzed(AnalyzerConfigOptions options)
            => IsTrue(options, "build_property.EnableTrimAnalyzer")
                || IsTrue(options, "build_property.EnableAotAnalyzer");

        private static bool IsTrue(AnalyzerConfigOptions options, string key)
            => options.TryGetValue(key, out var value) && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);
    }
}
