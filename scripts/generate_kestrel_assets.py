"""Generate the explicit application-local Kestrel component map (no shared framework)."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "src/EmbedIO.Kestrel"
RIDS = ("win-x64", "win-arm64", "linux-x64", "linux-arm64", "osx-x64", "osx-arm64")


def generate():
    names = json.loads((PROJECT / "components.json").read_text(encoding="utf-8"))
    pins = json.loads((PROJECT / "upstream-packs.json").read_text(encoding="utf-8"))
    version = pins["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("Invalid upstream version")
    expected = {"Microsoft.AspNetCore.App.Ref"} | {"Microsoft.AspNetCore.App.Runtime." + rid for rid in RIDS}
    if set(pins["sha256"]) != expected or any(not re.fullmatch(r"[0-9A-F]{64}", value) for value in pins["sha256"].values()):
        raise ValueError("Expected exact official runtime and reference package SHA-256 pins")
    if names != sorted(set(names)) or any(not re.fullmatch(r"[A-Za-z0-9_.]+", name) for name in names):
        raise ValueError("Expected sorted unique assembly names")
    lines = ["<Project>", "  <!-- Generated by scripts/generate_kestrel_assets.py; official pinned components only. -->", "  <ItemGroup>"]
    for name in names:
        # Copy-local references also register each runtime assembly in a consuming
        # project's deps.json. Content files alone are not sufficient for CLR binding.
        lines.append(f'    <Reference Include="{name}"><HintPath>$(NuGetPackageRoot)microsoft.aspnetcore.app.runtime.$(KestrelBuildRuntimeIdentifier)/$(KestrelComponentVersion)/runtimes/$(KestrelBuildRuntimeIdentifier)/lib/net10.0/{name}.dll</HintPath><Private>true</Private></Reference>')
    lines.append("  </ItemGroup>")
    for rid in RIDS:
        lines.append(f'  <ItemGroup Condition="$(KestrelRuntimeIdentifiers.Contains(\'{rid}\'))">')
        for name in names:
            lines.append(f'    <None Include="$(NuGetPackageRoot)microsoft.aspnetcore.app.runtime.{rid}/$(KestrelComponentVersion)/runtimes/{rid}/lib/net10.0/{name}.dll" Pack="true" PackagePath="runtimes/{rid}/lib/net10.0/" />')
        lines.append("  </ItemGroup>")
    lines.extend(["</Project>", ""])
    lines[-2:-2] = [
        "  <ItemGroup>",
        *[f'    <_KestrelPinnedPack Include="$(NuGetPackageRoot){name.lower()}/$(KestrelComponentVersion)/{name.lower()}.$(KestrelComponentVersion).nupkg" ExpectedHash="{digest}"' +
          (f' Condition="$(KestrelRuntimeIdentifiers.Contains(\'{name.removeprefix("Microsoft.AspNetCore.App.Runtime.")}\'))"' if name != "Microsoft.AspNetCore.App.Ref" else "") + " />"
          for name, digest in sorted(pins["sha256"].items())],
        "  </ItemGroup>",
        '  <Target Name="VerifyKestrelUpstreamPacks" BeforeTargets="ResolveReferences;GenerateNuspec">',
        f'    <Error Condition="\'$(KestrelComponentVersion)\' != \'{version}\'" Text="Update and review the upstream package pins when servicing Kestrel." />',
        '    <GetFileHash Files="@(_KestrelPinnedPack)" Algorithm="SHA256"><Output TaskParameter="Items" ItemName="_KestrelVerifiedPack" /></GetFileHash>',
        '    <Error Condition="\'%(_KestrelVerifiedPack.FileHash)\' != \'%(_KestrelVerifiedPack.ExpectedHash)\'" Text="Pinned upstream package hash differs: %(_KestrelVerifiedPack.Identity)" />',
        "  </Target>",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    destination = PROJECT / "KestrelComponents.props"
    generated = generate()
    if args.write:
        destination.write_text(generated, encoding="utf-8", newline="\n")
    elif destination.read_text(encoding="utf-8") != generated:
        raise SystemExit("KestrelComponents.props differs; regenerate with --write")
    print("Kestrel component map is current")


if __name__ == "__main__":
    main()
