def file_bytes():
    return bytes((i * 31 + (i >> 8)) & 0xFF for i in range(FILE_LENGTH))


class Endpoint:
    def __init__(self, host, port, tls, authority):
        self.host, self.port, self.tls, self.authority = host, port, tls, authority

    def connect(self, timeout=5.0):
        sock = socket.create_connection((self.host, self.port), timeout=timeout)
        sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        if self.tls:
            context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
            context.check_hostname = False
            context.verify_mode = ssl.CERT_NONE  # Test certificate generated by the host.
            context.set_alpn_protocols(["h2"])
            sock = context.wrap_socket(sock, server_hostname="localhost")
            if sock.selected_alpn_protocol() != "h2":
                raise RuntimeError(f"ALPN selected {sock.selected_alpn_protocol()!r}")
        return sock


class FrameTrace:
    """Bounded record of frame headers in one direction, for failure reports."""

    NAMES = {0: "DATA", 1: "HEADERS", 2: "PRIORITY", 3: "RST_STREAM", 4: "SETTINGS", 5: "PUSH_PROMISE",
             6: "PING", 7: "GOAWAY", 8: "WINDOW_UPDATE", 9: "CONTINUATION", 16: "PRIORITY_UPDATE"}

    def __init__(self, direction, log, skip=0):
        self.direction, self.log, self.skip, self.buffer = direction, log, skip, b""
        self.started = time.monotonic()

    def feed(self, data):
        if self.skip:
            taken = min(self.skip, len(data))
            data, self.skip = data[taken:], self.skip - taken
        self.buffer += data
        while len(self.buffer) >= 9 and len(self.buffer) >= 9 + int.from_bytes(self.buffer[:3], "big"):
            length = int.from_bytes(self.buffer[:3], "big")
            kind, flags = self.buffer[3], self.buffer[4]
            stream = int.from_bytes(self.buffer[5:9], "big") & 0x7FFFFFFF
            payload = self.buffer[9:9 + length]
            detail = ""
            if kind == 4 and not flags & 1:
                detail = " " + ",".join(f"{int.from_bytes(payload[i:i + 2], 'big')}={int.from_bytes(payload[i + 2:i + 6], 'big')}"
                                        for i in range(0, len(payload) - 5, 6))
            elif kind == 8:
                detail = f" +{int.from_bytes(payload[:4], 'big') & 0x7FFFFFFF}"
            elif kind in (3, 7):
                detail = f" code={int.from_bytes(payload[-4:], 'big')}"
            self.log.append(f"{time.monotonic() - self.started:8.4f} {self.direction} {self.NAMES.get(kind, kind)} "
                            f"s={stream} f=0x{flags:02x} len={length}{detail}")
            del self.log[:-400]
            self.buffer = self.buffer[9 + length:]


class Client:
    """Single-threaded hyper-h2 client with explicit flow-controlled uploads."""

    def __init__(self, endpoint, settings=None, timeout=10.0):
        self.endpoint = endpoint
        self.sock = endpoint.connect()
        self.timeout = timeout
        self.conn = h2.connection.H2Connection(config=h2.config.H2Configuration(client_side=True, header_encoding=None))
        self.conn.initiate_connection()
        if settings:
            self.conn.update_settings(settings)
        self.streams = {}
        self.terminated = None
        self.closed = False
        self.trace = []
        self.sent_trace = FrameTrace("->", self.trace, skip=len(PREFACE))
        self.received_trace = FrameTrace("<-", self.trace)
        self.flush()

    def flush(self):
        data = self.conn.data_to_send()
        if data:
            self.sent_trace.feed(data)
            self.sock.sendall(data)

    def request(self, method, path, body=b"", headers=(), end=True):
        stream_id = self.conn.get_next_available_stream_id()
        header_list = [(b":method", method), (b":scheme", b"https" if self.endpoint.tls else b"http"),
                       (b":authority", self.endpoint.authority), (b":path", path)] + list(headers)
        if body:
            header_list.append((b"content-length", str(len(body)).encode()))
        self.conn.send_headers(stream_id, header_list, end_stream=not body and end)
        self.streams[stream_id] = {"status": None, "headers": [], "body": bytearray(), "ended": False, "reset": None,
                                   "pending": bytes(body), "end": end, "informational": []}
        self.pump_uploads()
        self.flush()
        return stream_id

    def pump_uploads(self):
        for stream_id, state in self.streams.items():
            while state["pending"] and state["reset"] is None and not state["ended"]:
                try:
                    window = self.conn.local_flow_control_window(stream_id)
                except h2.exceptions.StreamClosedError:
                    state["pending"] = b""
                    break
                size = min(window, self.conn.max_outbound_frame_size, len(state["pending"]))
                if size <= 0:
                    break
                chunk, state["pending"] = state["pending"][:size], state["pending"][size:]
                self.conn.send_data(stream_id, chunk, end_stream=not state["pending"] and state["end"])

    def reset(self, stream_id, code=8):
        self.conn.reset_stream(stream_id, error_code=code)
        self.streams[stream_id]["reset"] = ("client", code)
        self.streams[stream_id]["pending"] = b""
        self.flush()

    def receive(self, wait):
        if self.closed:
            return False
        ready, _, _ = select.select([self.sock], [], [], wait)
        if not ready:
            return True
        try:
            data = self.sock.recv(65536)
        except (ConnectionResetError, ssl.SSLError, OSError):
            data = b""
        if not data:
            self.closed = True
            return False
        self.received_trace.feed(data)
        for event in self.conn.receive_data(data):
            self.handle(event)
        self.pump_uploads()
        self.flush()
        return True

    def handle(self, event):
        if isinstance(event, h2.events.ResponseReceived):
            state = self.streams[event.stream_id]
            state["headers"] = event.headers
            state["status"] = int(dict(event.headers)[b":status"])
        elif isinstance(event, h2.events.InformationalResponseReceived):
            self.streams[event.stream_id]["informational"].append(int(dict(event.headers)[b":status"]))
        elif isinstance(event, h2.events.DataReceived):
            self.streams[event.stream_id]["body"].extend(event.data)
            if event.flow_controlled_length:
                self.conn.acknowledge_received_data(event.flow_controlled_length, event.stream_id)
        elif isinstance(event, h2.events.StreamEnded):
            self.streams[event.stream_id]["ended"] = True
        elif isinstance(event, h2.events.StreamReset):
            if event.stream_id in self.streams and self.streams[event.stream_id]["reset"] is None:
                self.streams[event.stream_id]["reset"] = ("server", event.error_code)
        elif isinstance(event, h2.events.ConnectionTerminated):
            self.terminated = (int(event.error_code), event.last_stream_id, event.additional_data)

    def done(self, stream_id):
        state = self.streams[stream_id]
        return state["ended"] or state["reset"] is not None

    def wait(self, stream_ids, timeout=None):
        deadline = time.monotonic() + (timeout or self.timeout)
        while not all(self.done(s) for s in stream_ids):
            if time.monotonic() > deadline:
                raise TimeoutError(f"streams {[s for s in stream_ids if not self.done(s)]} incomplete")
            if not self.receive(0.05) and not all(self.done(s) for s in stream_ids):
                raise ConnectionError(f"connection closed; terminated={self.terminated}")

    def header(self, stream_id, name):
        for key, value in self.streams[stream_id]["headers"]:
            if key == name:
                return value
        return None

    def close(self):
        try:
            self.conn.close_connection()
            self.flush()
        except (OSError, h2.exceptions.ProtocolError):
            pass
        self.sock.close()


def raw_frames(sock, timeout):
    """Reads raw server frames until close or timeout; returns (frames, closed)."""
    buffer = b""
    frames = []
    deadline = time.monotonic() + timeout
    closed = False
    while time.monotonic() < deadline:
        ready, _, _ = select.select([sock], [], [], max(0.0, deadline - time.monotonic()))
        if not ready:
            break
        try:
            data = sock.recv(65536)
        except (ConnectionResetError, ssl.SSLError, OSError):
            data = b""
        if not data:
            closed = True
            break
        buffer += data
        while len(buffer) >= 9:
            length = int.from_bytes(buffer[:3], "big")
            if len(buffer) < 9 + length:
                break
            frame, _ = hf.Frame.parse_frame_header(memoryview(buffer[:9]))
            frame.parse_body(memoryview(buffer[9:9 + length]))
            frames.append(frame)
            buffer = buffer[9 + length:]
        if any(isinstance(f, hf.GoAwayFrame) for f in frames):
            # Drain briefly so closure after GOAWAY is observed.
            deadline = min(deadline, time.monotonic() + 1.0)
    return frames, closed


def raw_connection(endpoint):
    sock = endpoint.connect()
    sock.sendall(PREFACE + hf.SettingsFrame(0).serialize())
    return sock


def raw_headers_block(endpoint, path=b"/plain", method=b"GET"):
    import hpack
    encoder = hpack.Encoder()
    return encoder.encode([(b":method", method), (b":scheme", b"https" if endpoint.tls else b"http"),
                           (b":authority", endpoint.authority), (b":path", path)])


def goaway_code(frames):
    for f in frames:
        if isinstance(f, hf.GoAwayFrame):
            return f.error_code
    return None


def rst_codes(frames, stream_id=None):
    return [f.error_code for f in frames if isinstance(f, hf.RstStreamFrame) and (stream_id is None or f.stream_id == stream_id)]


def healthy(endpoint):
    try:
        client = Client(endpoint)
        stream_id = client.request(b"GET", b"/plain")
        client.wait([stream_id], 5)
        ok = client.streams[stream_id]["status"] == 200 and bytes(client.streams[stream_id]["body"]) == b"hello"
        client.close()
        return None if ok else f"status {client.streams[stream_id]['status']}"
    except Exception as error:  # Driver records every failure as evidence.
        return f"{type(error).__name__}: {error}"


def stats(host, port):
    try:
        return _stats(host, port)
    except OSError as error:  # A stopped listener is itself a recorded outcome.
        return {"error": f"{type(error).__name__}: {error}", "activeHandlers": 0, "handles": 0, "managedBytes": 0}


def _stats(host, port):
    """Reads /__stats over a cleartext HTTP/1.1 port with a minimal request."""
    with socket.create_connection((host, port), timeout=10) as sock:
        sock.sendall(f"GET /__stats HTTP/1.1\r\nHost: {host}:{port}\r\nConnection: close\r\n\r\n".encode())
        data = b""
        while True:
            chunk = sock.recv(65536)
            if not chunk:
                break
            data += chunk
    head, _, body = data.partition(b"\r\n\r\n")
    if b"transfer-encoding: chunked" in head.lower():
        decoded = b""
        while body:
            size_line, _, rest = body.partition(b"\r\n")
            size = int(size_line.split(b";")[0], 16)
            if size == 0:
                break
            decoded += rest[:size]
            body = rest[size + 2:]
        body = decoded
    return json.loads(body)


