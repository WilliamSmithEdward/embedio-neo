def run_fuzz(endpoint, seed, iterations, stats_port):
    """Random interleavings of opens, uploads, resets, window and settings changes."""
    rng = random.Random(seed)
    data = file_bytes()
    before = stats(endpoint.host, stats_port) if stats_port else None
    totals = {"streams": 0, "client_resets": 0, "server_resets": 0, "connections": 0}
    for iteration in range(iterations):
        log = []
        settings = {}
        if rng.random() < 0.3:
            settings[h2.settings.SettingCodes.INITIAL_WINDOW_SIZE] = rng.choice([0, 1, 100, 16384, 65535, 1 << 20])
        if rng.random() < 0.2:
            settings[h2.settings.SettingCodes.HEADER_TABLE_SIZE] = rng.choice([0, 64, 4096])
        if rng.random() < 0.2:
            settings[h2.settings.SettingCodes.MAX_FRAME_SIZE] = rng.choice([16384, 32768, 1 << 20])
        try:
            client = Client(endpoint, settings=settings or None)
            totals["connections"] += 1
            expected = {}
            for _ in range(rng.randint(1, 12)):
                action = rng.random()
                if action < 0.55 or not expected:
                    kind = rng.random()
                    if kind < 0.4:
                        body = rng.randbytes(rng.choice([0, 1, 100, 5000, 70000, 300000]))
                        sid = client.request(rng.choice([b"POST", b"PUT", b"QUERY"]) if body else b"POST",
                                             b"/echo", body, [(b"content-type", b"application/octet-stream")])
                        expected[sid] = ("echo", body)
                    elif kind < 0.6:
                        start = rng.randrange(FILE_LENGTH)
                        end = min(FILE_LENGTH - 1, start + rng.randrange(20000))
                        sid = client.request(b"GET", b"/files/data.bin", headers=[(b"range", f"bytes={start}-{end}".encode())])
                        expected[sid] = ("range", data[start:end + 1])
                    elif kind < 0.8:
                        n = rng.choice([0, 1, 16384, 100000])
                        sid = client.request(b"GET", f"/stream?n={n}&chunk={rng.choice([1, 700, 16384])}".encode())
                        expected[sid] = ("stream", bytes(i & 0xFF for i in range(n)))
                    else:
                        sid = client.request(rng.choice([b"GET", b"HEAD"]), b"/plain", headers=[(b"x-r", str(rng.random()).encode())] * rng.randint(0, 5))
                        expected[sid] = ("plain", None)
                    log.append(("open", sid))
                elif action < 0.7:
                    sid = rng.choice(list(expected))
                    if not client.done(sid):
                        client.reset(sid, rng.choice([0, 8, 2]))
                        totals["client_resets"] += 1
                        log.append(("reset", sid))
                elif action < 0.8:
                    client.conn.ping(rng.randbytes(8))
                    client.flush()
                    log.append(("ping",))
                elif action < 0.9:
                    client.conn.increment_flow_control_window(rng.randint(1, 1 << 20))
                    client.flush()
                    log.append(("window",))
                else:
                    client.conn.update_settings({h2.settings.SettingCodes.INITIAL_WINDOW_SIZE: rng.choice([0, 1000, 65535, 1 << 20])})
                    client.flush()
                    log.append(("settings",))
                for _ in range(rng.randint(0, 3)):
                    client.receive(0.01)
            # Any window left at zero is reopened so every live stream can complete.
            client.conn.update_settings({h2.settings.SettingCodes.INITIAL_WINDOW_SIZE: 65535})
            client.conn.increment_flow_control_window(1 << 24)
            client.flush()
            client.wait(list(expected), 30)
            for sid, (kind, body) in expected.items():
                state = client.streams[sid]
                totals["streams"] += 1
                if state["reset"] is not None:
                    if state["reset"][0] == "server":
                        totals["server_resets"] += 1
                        if state["reset"][1] not in (7, 8, 0):
                            raise AssertionError(f"stream {sid} reset by server with {ERROR_NAMES.get(state['reset'][1])}")
                    continue
                if kind == "plain":
                    if state["status"] != 200:
                        raise AssertionError(f"stream {sid} plain status {state['status']}")
                    continue
                if kind == "range" and state["status"] != 206:
                    raise AssertionError(f"stream {sid} range status {state['status']}")
                if bytes(state["body"]) != body:
                    raise AssertionError(f"stream {sid} {kind}: {len(state['body'])} of {len(body)} bytes; status {state['status']}")
            if client.terminated:
                raise AssertionError(f"server terminated a valid connection: {client.terminated}")
            client.close()
        except (BrokenPipeError, ConnectionResetError, ConnectionError) as error:
            return {"result": "FAIL", "seed": seed, "iteration": iteration, "error": f"{type(error).__name__}: {error}", "log": log,
                    "trace": client.trace if "client" in locals() else []}
        except Exception as error:  # A failed invariant is a finding with a replayable seed.
            return {"result": "FAIL", "seed": seed, "iteration": iteration, "settings": {int(k): v for k, v in settings.items()},
                    "error": f"{type(error).__name__}: {error}", "log": log,
                    "trace": client.trace if "client" in locals() else []}
        if (iteration + 1) % max(1, iterations // 5) == 0:
            health = healthy(endpoint)
            if health:
                return {"result": "FAIL", "seed": seed, "iteration": iteration, "error": "unhealthy: " + health}
    after = settle(endpoint, stats_port) if stats_port else None
    report = {"result": "PASS", "seed": seed, "iterations": iterations, "totals": totals,
              "stats_before": before, "stats_after": after}
    if before and after:
        report["handleGrowth"] = after["handles"] - before["handles"]
        report["managedGrowth"] = after["managedBytes"] - before["managedBytes"]
        if after["activeHandlers"] or report["handleGrowth"] > 64 or report["managedGrowth"] > 32 << 20:
            report["result"] = "FAIL"
            report["error"] = "resources did not settle"
    return report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=["cases", "fuzz"])
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--authority")
    parser.add_argument("--tls", action="store_true")
    parser.add_argument("--stats-port", type=int)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--iterations", type=int, default=200)
    parser.add_argument("--out")
    parser.add_argument("--only", help="run only cases whose id contains this text")
    args = parser.parse_args()
    global ONLY
    ONLY = args.only
    endpoint = Endpoint(args.host, args.port, args.tls, (args.authority or f"{args.host}:{args.port}").encode())
    import h2 as h2_package
    identity = {"h2": h2_package.__version__, "python": sys.version, "target": f"{args.host}:{args.port}", "tls": args.tls}
    if args.mode == "cases":
        report = run_cases(endpoint, args.stats_port)
        failed = any(o["result"] in ("violation", "error") for o in report["outcomes"])
        counts = {}
        for o in report["outcomes"]:
            counts[o["result"]] = counts.get(o["result"], 0) + 1
        print(counts)
    else:
        report = run_fuzz(endpoint, args.seed, args.iterations, args.stats_port)
        failed = report["result"] != "PASS"
        print(json.dumps(report)[:4000])
    report["identity"] = identity
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
            json.dump(report, handle, indent=1, ensure_ascii=True)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
