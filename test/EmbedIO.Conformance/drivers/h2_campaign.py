def run_cases(endpoint, stats_port):
    results = []
    before = stats(endpoint.host, stats_port) if stats_port else None
    for identifier, reference, level, function in CASES:
        if ONLY and ONLY not in identifier:
            continue
        started = time.monotonic()
        try:
            result, detail = function(endpoint)
        except Exception as error:  # Recorded as an error outcome.
            result, detail = "error", f"{type(error).__name__}: {error}"
        health = healthy(endpoint)
        if health:
            result, detail = "violation", f"{detail}; UNHEALTHY AFTER CASE: {health}"
        results.append({"id": identifier, "reference": reference, "level": level, "result": result,
                        "detail": detail, "seconds": round(time.monotonic() - started, 3)})
        print(f"{result:<10} {identifier:<28} {level:<7} {reference:<32} {detail}", flush=True)
    after = settle(endpoint, stats_port) if stats_port else None
    return {"outcomes": results, "stats_before": before, "stats_after": after}


def settle(endpoint, stats_port):
    snapshot = stats(endpoint.host, stats_port)
    for _ in range(50):
        if snapshot["activeHandlers"] == 0:
            break
        time.sleep(0.1)
        snapshot = stats(endpoint.host, stats_port)
    return snapshot


