@case(CASES, "settings-shrink-ordering", "RFC9113 6.5.3; 6.9.2", "MUST")
def _(e):
    # Independent window accounting with raw frames: once the server ACKs a smaller
    # SETTINGS_INITIAL_WINDOW_SIZE, its later DATA must fit the adjusted window.
    worst = 0
    trials = 40
    for trial in range(trials):
        sock = raw_connection(e)
        h = hf.HeadersFrame(1, raw_headers_block(e, b"/stream?n=4000000&chunk=16000"))
        h.flags.add("END_HEADERS")
        h.flags.add("END_STREAM")
        # Large connection window so only the stream window governs.
        sock.sendall(h.serialize() + hf.WindowUpdateFrame(0, window_increment=1 << 30).serialize())
        window = 65535
        acked = False
        acks = 0  # ACKs arrive in SETTINGS order; the second answers the shrink.
        sent_shrink = False
        new_size = [0, 1, 1000, 8000][trial % 4]
        buffer = b""
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline:
            ready, _, _ = select.select([sock], [], [], 0.2)
            if not ready:
                if acked:
                    break
                continue
            data = sock.recv(65536)
            if not data:
                break
            buffer += data
            while len(buffer) >= 9 and len(buffer) >= 9 + int.from_bytes(buffer[:3], "big"):
                length = int.from_bytes(buffer[:3], "big")
                frame_type, flags = buffer[3], buffer[4]
                buffer = buffer[9 + length:]
                if frame_type == 0x0:
                    window -= length
                    if acked and window < worst:
                        worst = window
                    if not sent_shrink and window < 65535 - 16000 * (trial % 3):
                        sock.sendall(hf.SettingsFrame(0, settings={4: new_size}).serialize())
                        sent_shrink = True
                elif frame_type == 0x4 and flags & 1:
                    acks += 1
                    if acks == 2:
                        acked = True
                        window += new_size - 65535
        sock.close()
    return ("conforms" if worst >= 0 else "violation",
            f"{trials} trials; most negative stream window observed after SETTINGS ACK: {worst}")


@case(CASES, "settings-pair-ordering", "RFC9113 6.5.3; 6.9.2", "MUST")
def _(e):
    # Close the stream window with one SETTINGS, reopen it with a second. DATA the
    # server writes between the two ACKs exceeds the window the client has applied.
    violations = 0
    worst = 0
    trials = 60
    for trial in range(trials):
        sock = raw_connection(e)
        h = hf.HeadersFrame(1, raw_headers_block(e, b"/stream?n=4000000&chunk=16000"))
        h.flags.add("END_HEADERS")
        h.flags.add("END_STREAM")
        sock.sendall(h.serialize() + hf.WindowUpdateFrame(0, window_increment=1 << 30).serialize())
        window = 65535
        acks = 0
        sent = False
        trigger = [0, 16384, 40000][trial % 3]
        buffer = b""
        overrun = False
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline and acks < 3:
            ready, _, _ = select.select([sock], [], [], 0.2)
            if not ready:
                continue
            data = sock.recv(65536)
            if not data:
                break
            buffer += data
            while len(buffer) >= 9 and len(buffer) >= 9 + int.from_bytes(buffer[:3], "big"):
                length = int.from_bytes(buffer[:3], "big")
                frame_type, flags = buffer[3], buffer[4]
                buffer = buffer[9 + length:]
                if frame_type == 0x0:
                    window -= length
                    if window < 0:
                        overrun = True
                        worst = min(worst, window)
                    if not sent and 65535 - window >= trigger:
                        sock.sendall(hf.SettingsFrame(0, settings={4: 0}).serialize() + hf.SettingsFrame(0, settings={4: 65535}).serialize())
                        sent = True
                elif frame_type == 0x4 and flags & 1:
                    acks += 1
                    if acks == 2:
                        window -= 65535  # Applied: INITIAL_WINDOW_SIZE 65535 -> 0.
                    elif acks == 3:
                        window += 65535  # Applied: 0 -> 65535.
        violations += overrun
        sock.close()
    return ("conforms" if violations == 0 else "violation",
            f"{violations} of {trials} trials received DATA beyond the acknowledged window (worst {worst})")


@case(CASES, "reset-while-responding", "RFC9113 5.4.2; 6.4", "MUST")
def _(e):
    # Minimized from h2 fuzz seed 20261009: RST_STREAM on a request whose response may be
    # in progress is a stream-level event; the connection must survive and answer PING.
    import hpack
    rng = random.Random(1309)
    dropped = []
    trials = 300
    for trial in range(trials):
        sock = raw_connection(e)
        encoder = hpack.Encoder()
        path = rng.choice([b"/plain", b"/stream?n=100000&chunk=700", b"/files/data.bin", b"/slow?ms=5"])
        first = hf.HeadersFrame(1, encoder.encode([(b":method", b"GET"), (b":scheme", b"http"), (b":authority", e.authority), (b":path", path)]))
        first.flags.add("END_HEADERS")
        first.flags.add("END_STREAM")
        second = hf.HeadersFrame(3, encoder.encode([(b":method", b"POST"), (b":scheme", b"http"), (b":authority", e.authority),
                                                    (b":path", b"/echo"), (b"content-length", b"100")]))
        second.flags.add("END_HEADERS")
        body = hf.DataFrame(3, b"b" * 100)
        body.flags.add("END_STREAM")
        sock.sendall(first.serialize() + second.serialize() + body.serialize())
        time.sleep(rng.choice([0, 0, 0.0005, 0.001, 0.003]))
        code = rng.choice([0, 8])
        try:
            sock.sendall(hf.RstStreamFrame(1, code).serialize() + hf.PingFrame(0, opaque_data=b"embedio!").serialize())
        except OSError:
            dropped.append((trial, path.decode(), code, "send failed"))
            sock.close()
            continue
        frames, closed = raw_frames(sock, 1.5)
        acked = any(isinstance(f, hf.PingFrame) and "ACK" in f.flags for f in frames)
        if not acked:
            dropped.append((trial, path.decode(), code, f"closed={closed} goaway={goaway_code(frames)}"))
        sock.close()
    return ("conforms" if not dropped else "violation",
            f"{len(dropped)} of {trials} connections lost after RST_STREAM; first: {dropped[:5]}")


